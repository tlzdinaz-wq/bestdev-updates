local cosmeticKeywords = {"VARMOD","LUXE","CAMO","LOWRIDER","DIGICAM","BRUSHSTROKE","WOODLAND","SKULL","SESSANTA","PERSEUS","LEOPARD","ZEBRA","GEOMETRIC","BOOM","PATRIOT"}

function GetItemFromHash(componentHash)
    return ComponentHashToItem[componentHash]
end

function GetComponentCategory(componentHash)
    if string.find(componentHash, "_CLIP") or string.find(componentHash, "_MAG") then return "clip" end
    if string.find(componentHash, "_SCOPE") or string.find(componentHash, "_SIGHTS") or string.find(componentHash, "_SIGHT_") or string.find(componentHash, "_RAIL") then return "scope" end
    if string.find(componentHash, "_SUPP") then return "suppressor" end
    if string.find(componentHash, "_COMP") then return "compensator" end
    if string.find(componentHash, "_MUZZLE") then return "muzzle" end
    if string.find(componentHash, "_BARREL") then return "barrel" end
    if string.find(componentHash, "_FLSH") then return "flashlight" end
    if string.find(componentHash, "_AFGRIP") then return "grip" end
    return nil
end

function IsCosmeticComponent(componentHash)
    local hash = tostring(componentHash):upper()
    for _, kw in ipairs(cosmeticKeywords) do
        if string.find(hash, kw) then return true end
    end
    return false
end

function IsComponentEquippedOnWeapon(equippedComponents, componentHash)
    if not equippedComponents then return false end
    for _, comp in ipairs(equippedComponents) do
        if comp == componentHash or comp == tostring(componentHash) then
            return true
        end
    end
    return false
end
